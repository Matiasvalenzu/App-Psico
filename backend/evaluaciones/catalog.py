TESTS = {ELLIS_SLUG: ELLIS_TEST}


def list_tests():
    return [without_scoring(test) for test in TESTS.values()]


def get_test(slug):
    return TESTS.get(slug)


def without_scoring(test):
    public_questions = [
        {"id": question["id"], "text": question["text"]}
        for question in test["questions"]
    ]
    return {
        **test,
        "questions": public_questions,
    }


def get_level(score):
    if score >= 7:
        return {
            "level": "ALTO",
            "label": "Creencia limitante en muchas áreas de la vida",
        }
    if score >= 5:
        return {
            "level": "MODERADO",
            "label": "Creencia limitante en determinadas circunstancias",
        }
    return {
        "level": "BAJO",
        "label": "Sin elevación clínicamente destacada según el criterio del instrumento",
    }


def evaluate_ellis(responses):
    question_map = {question["id"]: question for question in ELLIS_QUESTIONS}
    normalized = {int(key): value for key, value in responses.items()}
    scores_by_question = {}

    for question_id, question in question_map.items():
        response = normalized.get(question_id)
        scores_by_question[str(question_id)] = 1 if response == question["score_on"] else 0

    dimensions = []
    for dimension in ELLIS_DIMENSIONS:
        score = sum(scores_by_question[str(question_id)] for question_id in dimension["questions"])
        level = get_level(score)
        dimensions.append(
            {
                "id": dimension["id"],
                "name": dimension["name"],
                "belief": dimension["belief"],
                "questions": dimension["questions"],
                "score": score,
                **level,
            }
        )

    sorted_dimensions = sorted(dimensions, key=lambda item: item["score"], reverse=True)
    return {
        "test_slug": ELLIS_SLUG,
        "test_name": ELLIS_TEST["name"],
        "total_score": sum(item["score"] for item in dimensions),
        "max_score": 100,
        "dimensions": dimensions,
        "highest_dimensions": sorted_dimensions[:3],
        "scores_by_question": scores_by_question,
    }
